#!/usr/bin/env python3
"""
Turns the_red.jpeg into src/Logo.html (an <img> with the logo embedded as a
data URI). Apps Script web apps can't serve image files, so the logo is inlined.

    python3 tools/build_logo.py [path/to/logo.jpeg]

Re-run it whenever the logo image changes, then paste src/Logo.html into Apps Script.
"""
import base64
import io
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "the_red.jpeg"
HEIGHT = 112  # 2× the displayed header height, so it stays sharp on retina screens

img = Image.open(SOURCE).convert("RGB")
width = round(img.width * HEIGHT / img.height)
img = img.resize((width, HEIGHT), Image.LANCZOS)
buf = io.BytesIO()
img.save(buf, "JPEG", quality=88, optimize=True)
data = base64.b64encode(buf.getvalue()).decode("ascii")

html = (
    "<!-- Generated by tools/build_logo.py from " + SOURCE.name + ". Do not edit by hand. -->\n"
    f'<img class="logo-image" src="data:image/jpeg;base64,{data}" alt="" width="{width // 2}" height="{HEIGHT // 2}">\n'
)
(ROOT / "src" / "Logo.html").write_text(html, encoding="utf-8")
print(f"Wrote src/Logo.html ({width}x{HEIGHT}px, {len(buf.getvalue()) // 1024} KB)")
